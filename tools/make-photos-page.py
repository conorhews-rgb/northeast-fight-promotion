#!/usr/bin/env python3
"""Build src/pages/photos.html, the Fight Photos page.

One card per Pixieset set, in card order, each opening that set in a new tab.
Covers are web-sized copies in assets/img/photos/. For a new event, add a
block to EVENTS (newest first), drop its covers in, and run:

    python3 tools/make-photos-page.py && python3 build.py
"""
BASE = "https://paperviewproductions.pixieset.com/nfp1/"
EVENTS = [
    {
        "name": "NFP 1",
        "meta": "Sat, Oct 24 2026 / Nashua Community College",
        "gallery": BASE,
        "sets": [   # (pixieset slug, label shown on the site)
            ("barryvsteauge", "Barry vs Teague"),
            ("ferrivssmythe", "Ferri vs Smythe"),
            ("walshvszahir", "Walsh vs Zahir"),
            ("faganvsjohnson", "Fagan vs Johnson"),
            ("kimvscolon", "Kim vs Colon"),
            ("cetoutevsduffy", "Cetoute vs Duffy"),
            ("kellyvsstfelix", "Kelly vs St. Felix"),
            ("drazhanvsacuna", "Drazhan vs Acuna"),
            ("bernardvssilva", "Bernard vs Silva"),
            ("pacyvsjuarez", "Pacy vs Juarez"),
            ("connertonvsstocker", "Connerton vs Stocker"),
            ("mackeyvsburbach", "Mackey vs Burbach"),
            ("extras", "Around the night"),
        ],
    },
]


def card(gallery, slug, label):
    return f'''      <a class="photo-set" href="{gallery}{slug}/" target="_blank" rel="noopener" data-reveal>
        <img src="assets/img/photos/nfp1-{slug}.jpg" alt="{label}, NFP 1" width="720" height="480" loading="lazy">
        <span class="photo-set-label">{label}<span class="arw" aria-hidden="true">&rarr;</span></span>
      </a>'''


def main():
    blocks = []
    for ev in EVENTS:
        cards = "\n".join(card(ev["gallery"], s, l) for s, l in ev["sets"])
        meta = ev["meta"].replace(" / ", ' <span class="sep">/</span> ')
        blocks.append(f'''<section class="section">
  <div class="wrap">
    <div class="section-head">
      <div data-reveal>
        <span class="bar"></span>
        <h2>{ev["name"]}</h2>
        <p class="meta">{meta}</p>
      </div>
      <a class="btn" href="{ev["gallery"]}" target="_blank" rel="noopener" data-reveal="right">Full gallery</a>
    </div>

    <div class="photo-sets" data-stagger="60">
{cards}
    </div>
  </div>
</section>''')
    html = '''<!--{"slug": "photos", "title": "Fight Photos | Northeast Fight Promotion", "desc": "Fight photos from Northeast Fight Promotion events by Paperview Productions, bout by bout. Prints and downloads available."}-->
<!-- Generated by tools/make-photos-page.py. Edit the EVENTS table there. -->
<!-- ===================== PAGE HERO ===================== -->
<section class="page-hero">
  <img class="region" src="assets/img/region.png" alt="" aria-hidden="true" data-parallax="0.06">
  <div class="wrap">
    <p class="crumbs"><a href="index.html">Home</a><span>/</span>Fight Photos</p>
    <h1>Fight photos</h1>
    <p class="lede">
      Every bout, shot by Paperview Productions. Pick a fight to see the full set.
      Prints and downloads are available in the gallery.
    </p>
  </div>
</section>

''' + "\n\n".join(blocks) + "\n\n{{> notify}}\n"
    open("src/pages/photos.html", "w").write(html)
    print("wrote src/pages/photos.html:", sum(len(e["sets"]) for e in EVENTS), "sets")


if __name__ == "__main__":
    main()
